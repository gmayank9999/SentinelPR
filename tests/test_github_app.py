"""GitHub App authentication: the only supported way to create a Check Run. GitHub is always an in-memory transport here, and the
signing key is generated by the test, so no real App, key or token is involved."""

import base64
import calendar
import json
import sys
import time

import httpx
import pytest
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding, rsa

from sentinel.publish import app_auth
from sentinel.publish.app_auth import AppAuthError, AppConfig, GitHubAppAuth, make_jwt

NOW = 1_800_000_000.0
FAKE_INSTALL_TOKEN = "ghs_" + "T0kenFromGitHub9" * 2


@pytest.fixture(scope="module")
def key():
    return rsa.generate_private_key(public_exponent=65537, key_size=2048)


@pytest.fixture()
def pem(tmp_path, key):
    path = tmp_path / "app.pem"
    path.write_bytes(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.TraditionalOpenSSL, serialization.NoEncryption()))
    return path


def unb64(part):
    return base64.urlsafe_b64decode(part + "=" * (-len(part) % 4))


class FakeGitHub:
    def __init__(self, routes):
        self.routes, self.requests = routes, []

    def client(self):
        def handler(request):
            self.requests.append(request)
            for (method, path), answer in self.routes.items():
                if request.method == method and request.url.path == path:
                    return answer(request) if callable(answer) else answer
            return httpx.Response(404, json={"message": "Not Found"})

        return httpx.Client(base_url="https://api.github.com", transport=httpx.MockTransport(handler))


def auth(pem, routes, now=NOW, **cfg):
    gh = FakeGitHub(routes)
    clock = lambda: now  # noqa: E731
    return GitHubAppAuth(AppConfig("Iv1.abc123", pem, **cfg), gh.client(), clock=clock), gh


TOKEN_ROUTE = {("GET", "/repos/o/r/installation"): httpx.Response(200, json={"id": 777}),
               ("POST", "/app/installations/777/access_tokens"): httpx.Response(201, json={"token": FAKE_INSTALL_TOKEN, "expires_at": "2027-01-15T09:10:00Z"})}


# --- the JWT follows GitHub's rules -------------------------------------------------------------------------------------------


def test_the_jwt_is_rs256_with_a_backdated_iat_a_short_exp_and_a_valid_signature(pem, key):
    token = make_jwt(AppConfig("Iv1.abc123", pem), now=NOW)
    header, claims, signature = token.split(".")
    assert json.loads(unb64(header)) == {"alg": "RS256", "typ": "JWT"}
    payload = json.loads(unb64(claims))
    assert payload == {"iat": int(NOW) - 60, "exp": int(NOW) + 540, "iss": "Iv1.abc123"}
    assert payload["exp"] - int(NOW) <= 600  # GitHub rejects anything beyond ten minutes
    key.public_key().verify(unb64(signature), f"{header}.{claims}".encode(), padding.PKCS1v15(), hashes.SHA256())  # raises if the signature is wrong


def test_a_different_key_does_not_verify(pem):
    other = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    header, claims, signature = make_jwt(AppConfig("x", pem), now=NOW).split(".")
    with pytest.raises(Exception):
        other.public_key().verify(unb64(signature), f"{header}.{claims}".encode(), padding.PKCS1v15(), hashes.SHA256())


# --- configuration comes from the environment, and only as a file path ------------------------------------------------------------


def test_configuration_reads_the_environment_and_never_the_key_itself(monkeypatch, tmp_path):
    for name in ("SENTINEL_GITHUB_APP_CLIENT_ID", "SENTINEL_GITHUB_APP_ID", "SENTINEL_GITHUB_APP_PRIVATE_KEY_PATH", "SENTINEL_GITHUB_APP_INSTALLATION_ID"):
        monkeypatch.delenv(name, raising=False)
    cfg = AppConfig.from_env()
    assert cfg.configured is False and len(cfg.problems()) == 2
    monkeypatch.setenv("SENTINEL_GITHUB_APP_ID", "12345")
    monkeypatch.setenv("SENTINEL_GITHUB_APP_PRIVATE_KEY_PATH", str(tmp_path / "missing.pem"))
    cfg = AppConfig.from_env()
    assert cfg.issuer == "12345" and cfg.configured and "does not point to an existing file" in cfg.problems()[0]
    monkeypatch.setenv("SENTINEL_GITHUB_APP_CLIENT_ID", "Iv1.client")
    monkeypatch.setenv("SENTINEL_GITHUB_APP_INSTALLATION_ID", "99")
    cfg = AppConfig.from_env()
    assert cfg.issuer == "Iv1.client" and cfg.installation_id == 99  # the client id is preferred, as GitHub recommends


def test_bad_keys_are_explained(tmp_path, pem):
    bad = tmp_path / "bad.pem"
    bad.write_text("-----BEGIN RSA PRIVATE KEY-----\nnot a key\n-----END RSA PRIVATE KEY-----\n")
    with pytest.raises(AppAuthError) as err:
        make_jwt(AppConfig("x", bad), now=NOW)
    assert err.value.code == "key_invalid" and "unencrypted PEM" in err.value.message
    with pytest.raises(AppAuthError) as err:
        make_jwt(AppConfig("x", tmp_path / "nope.pem"), now=NOW)
    assert err.value.code == "key_missing"
    ec = tmp_path / "ec.pem"
    from cryptography.hazmat.primitives.asymmetric import ec as ecmod

    ec.write_bytes(ecmod.generate_private_key(ecmod.SECP256R1()).private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    with pytest.raises(AppAuthError) as err:
        make_jwt(AppConfig("x", ec), now=NOW)
    assert "not an RSA key" in err.value.message


def test_a_missing_crypto_library_gives_an_actionable_error(monkeypatch, pem):
    monkeypatch.setitem(sys.modules, "cryptography.hazmat.primitives", None)
    with pytest.raises(AppAuthError) as err:
        app_auth.load_private_key(pem)
    assert err.value.code == "crypto_missing" and "pip install cryptography" in err.value.fix


# --- installation token: least privilege, caching, refresh ----------------------------------------------------------------------------


def test_the_installation_token_is_requested_with_the_jwt_for_one_repo_and_checks_only(pem):
    a, gh = auth(pem, dict(TOKEN_ROUTE))
    assert a.token("o/r") == FAKE_INSTALL_TOKEN
    install, mint = gh.requests
    assert install.url.path == "/repos/o/r/installation" and install.headers["authorization"].startswith("Bearer eyJ")
    assert mint.url.path == "/app/installations/777/access_tokens" and mint.method == "POST"
    assert json.loads(mint.content) == {"repositories": ["r"], "permissions": {"checks": "write"}}
    assert mint.headers["authorization"].startswith("Bearer eyJ") and FAKE_INSTALL_TOKEN not in mint.headers["authorization"]  # the JWT mints it, never the reverse


def test_tokens_are_cached_until_shortly_before_they_expire(pem):
    expires = calendar.timegm(time.strptime("2027-01-15T09:10:00", "%Y-%m-%dT%H:%M:%S"))  # GitHub reports expiry in UTC
    a, gh = auth(pem, dict(TOKEN_ROUTE), now=expires - 3000)
    a.token("o/r")
    a.token("o/r")
    assert len([r for r in gh.requests if r.method == "POST"]) == 1 and len([r for r in gh.requests if r.url.path.endswith("/installation")]) == 1
    a.clock = lambda: expires - 100  # inside the five-minute refresh window
    a.token("o/r")
    assert len([r for r in gh.requests if r.method == "POST"]) == 2


def test_a_configured_installation_id_skips_discovery(pem):
    a, gh = auth(pem, {k: v for k, v in TOKEN_ROUTE.items() if k[0] == "POST"}, installation_id=777)
    a.token("o/r")
    assert [r.url.path for r in gh.requests] == ["/app/installations/777/access_tokens"]


@pytest.mark.parametrize("status,step,code,needle", [
    (401, "GET", "jwt_rejected", "clock"), (404, "GET", "not_installed", "Install App"), (422, "POST", "permissions_not_granted", "Checks → Read and write")])
def test_every_failure_is_explained_with_the_fix(pem, status, step, code, needle):
    routes = dict(TOKEN_ROUTE)
    routes[("GET" if step == "GET" else "POST", "/repos/o/r/installation" if step == "GET" else "/app/installations/777/access_tokens")] = httpx.Response(status, json={"message": "boom"})
    a, _ = auth(pem, routes)
    with pytest.raises(AppAuthError) as err:
        a.token("o/r")
    assert err.value.code == code and needle in (err.value.message + err.value.fix)


def test_network_failure_is_reported(pem):
    def down(request):
        raise httpx.ConnectError("no route")

    a, _ = auth(pem, {("GET", "/repos/o/r/installation"): down})
    with pytest.raises(AppAuthError) as err:
        a.token("o/r")
    assert err.value.code == "unreachable"


def test_nothing_secret_appears_in_errors_or_descriptions(pem, key, caplog):
    routes = {**TOKEN_ROUTE, ("GET", "/app"): httpx.Response(200, json={"name": "SentinelPR Gate", "slug": "sentinelpr-gate", "html_url": "https://github.com/apps/sentinelpr-gate",
                                                                      "permissions": {"checks": "write", "metadata": "read"}})}
    a, _ = auth(pem, routes)
    a.token("o/r")
    described = a.describe("o/r")
    blob = json.dumps(described) + caplog.text
    assert FAKE_INSTALL_TOKEN not in blob and "BEGIN" not in blob and "eyJ" not in blob
    assert described["checks_write"] is True and described["installation"] == {"id": 777, "repository": "o/r"} and described["app"]["slug"] == "sentinelpr-gate"


def test_describe_flags_an_app_without_checks_permission(pem):
    a, _ = auth(pem, {**TOKEN_ROUTE, ("GET", "/app"): httpx.Response(200, json={"name": "n", "slug": "s", "html_url": "u", "permissions": {"metadata": "read"}})})
    d = a.describe("o/r")
    assert d["checks_write"] is False and any("Checks: Read and write" in p for p in d["problems"])


